def test_error_messages_match_legacy_fixture(fixture):
    contexts = build_contexts(
        {
            code: entry
            for code, entry in fixture["context_spec"].items()
            if code != "V00"
        }
    )
    # Panels are seeded, so seed 11/n 32 from the generator is reproduced by
    # reusing a stored panel that contains V00 rows instead.
    panel = fixture["panels"][0]
    observations = observations_from_flat(
        panel["observations"], make_representable=True
    )
    assert "V00" in observations.stn.to_pylist()
    with pytest.raises(ValueError) as exc_info:
        ADES_to_string(observations, contexts)
    assert str(exc_info.value) == fixture["errors"]["missing_context"]

    no_ids = ADESObservations.from_kwargs(
        obsTime=Timestamp.from_mjd([60434.0], scale="utc"),
        ra=[10.0],
        dec=[-5.0],
        stn=["695"],
        mode=["CCD"],
        astCat=["Gaia2"],
    )
    with pytest.raises(ValueError) as exc_info:
        ADES_to_string(no_ids, build_contexts(fixture["context_spec"]))
    assert str(exc_info.value) == fixture["errors"]["missing_ids"]
